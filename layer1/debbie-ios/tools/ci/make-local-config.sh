#!/usr/bin/env bash
# Writes Config/Local.xcconfig (gitignored) from ~/.config/debbie-ios/asc.env (D-002).
# Only BUNDLE_ID and APPLE_TEAM_ID go in it: neither is a secret. The ASC key values are never read here.
set -euo pipefail
cd "$(dirname "$0")/../.."
ENV_FILE="$HOME/.config/debbie-ios/asc.env"
[[ -f "$ENV_FILE" ]] || { echo "BLOCKED: $ENV_FILE is missing; keeping the placeholder identifiers"; exit 1; }
# Accepts NAME=value and export NAME=value, like tools/ci/fl, which sources the same file.
# A missing line gives an empty value (never an abort under pipefail), and a trailing "# comment" is dropped.
value() { { grep -E "^(export )?$1=" "$ENV_FILE" || true; } | head -1 | sed -E "s/^(export )?$1=//; s/[[:space:]]+#.*$//" | tr -d '"'"'"' '; }
BUNDLE_ID="$(value BUNDLE_ID)"
APPLE_TEAM_ID="$(value APPLE_TEAM_ID)"
[[ -n "$BUNDLE_ID" && -n "$APPLE_TEAM_ID" ]] || { echo "BLOCKED: BUNDLE_ID or APPLE_TEAM_ID is missing in asc.env"; exit 1; }
cat > Config/Local.xcconfig <<CFG
// Generated by tools/ci/make-local-config.sh from asc.env (and gemini.env). Gitignored.
// The bundle ID and team ID aren't secret (D-002). The Gemini key is: it's built into TestFlight builds by the owner's
// decision (D-031) and is never committed, printed or logged.
DEBBIE_BUNDLE_ID = $BUNDLE_ID
DEBBIE_TEAM_ID = $APPLE_TEAM_ID
CFG
GEMINI_FILE="$HOME/.config/debbie-ios/gemini.env"
if [[ -f "$GEMINI_FILE" ]]; then
  ENV_FILE="$GEMINI_FILE"
  GEMINI_KEY="$(value GEMINI_API_KEY)"; GEMINI_MODEL="$(value GEMINI_MODEL)"
  [[ -n "$GEMINI_KEY" ]] && echo "DEBBIE_GEMINI_KEY = $GEMINI_KEY" >> Config/Local.xcconfig
  [[ -n "$GEMINI_MODEL" ]] && echo "DEBBIE_GEMINI_MODEL = $GEMINI_MODEL" >> Config/Local.xcconfig
  echo "✓ Config/Local.xcconfig written (bundle ID, team ID$([[ -n "$GEMINI_KEY" ]] && echo ', Gemini key'))"
else
  echo "✓ Config/Local.xcconfig written (bundle ID and team ID; no gemini.env, so Debbie uses on-device answers)"
fi
