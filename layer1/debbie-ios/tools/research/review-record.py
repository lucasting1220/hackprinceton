#!/usr/bin/env python3
"""Builds docs/research/research-review.md (the Phase 1 independent-review record) from the
research workflow's journal and each note's "## Review log" section.

Usage: python3 -I tools/research/review-record.py <workflow journal.jsonl>
"""
import ast
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
NOTES = {
    "featured": ["01-featured-apps-craft.md"],
    "ios26": ["02-ios-design-language.md", "13-platform-extras.md"],
    "motion": ["03-motion-springs.md", "05-transitions.md"],
    "haptics": ["04-haptics.md", "09-buttons-controls.md"],
    "colour": ["06-colour.md", "07-typography-layout.md"],
    "icons": ["08-icons-logos-app-icons.md"],
    "care": ["10-caregivers-older-adults-alerting.md"],
    "eng-a": ["11a-engineering-architecture.md"],
    "eng-b": ["11b-engineering-webrtc-testing-perf.md"],
    "delivery": ["12-delivery-fastlane.md"],
}


def parse(result):
    if isinstance(result, dict):
        return result
    if isinstance(result, str):
        for loader in (json.loads, ast.literal_eval):
            try:
                return loader(result)
            except Exception:  # noqa: BLE001
                pass
    return {}


def main():
    journal = sys.argv[1]
    started, results = {}, {}
    with open(journal, encoding="utf-8") as fh:
        for line in fh:
            try:
                d = json.loads(line)
            except Exception:  # noqa: BLE001
                continue
            if d.get("type") == "started":
                started[d["agentId"]] = d.get("label", "")
            elif d.get("type") == "result":
                results[d["agentId"]] = parse(d.get("result"))
    by_label = {started[a]: r for a, r in results.items() if a in started}
    out = ["# Phase 1 independent review record", "",
           "_Generated by `tools/research/review-record.py` from the research workflow journal and the notes' review logs._", "",
           "Method (brief §8 Phase 1): every note went to a **fresh reviewer with no stake**, told to find problems, not praise. Each reviewer spot-checked cited URLs, checked every recommended API against the local iOS 26.5 SDK, and hunted for unsourced claims, contradictions, undated sources, topic gaps, uncheckable recommendations and unflagged iOS changes. A separate fixer then fixed each finding or rejected it with evidence, and appended a `## Review log` to the note.", "",
           "| Research agent | Notes | Findings (high / medium / low) | Fixer result | Review log in note |", "|---|---|---|---|---|"]
    details = []
    for key, files in NOTES.items():
        rev = by_label.get(f"review:{key}", {})
        fix = by_label.get(f"fix:{key}", {})
        f = rev.get("findings", []) if isinstance(rev, dict) else []
        sev = {s: sum(1 for x in f if x.get("severity") == s) for s in ("high", "medium", "low")}
        logs = []
        for name in files:
            path = os.path.join(ROOT, "docs", "research", name)
            has = os.path.exists(path) and "## Review log" in open(path, encoding="utf-8").read()
            logs.append(f"{name}: {'yes' if has else 'NO'}")
        reviewed = f"review:{key}" in by_label
        if not reviewed:
            fixed, counts = "review PENDING", "review PENDING"
        else:
            counts = f"{len(f)} ({sev['high']} / {sev['medium']} / {sev['low']})"
            fixed = (f"{fix.get('fixed', '—')} fixed, {fix.get('rejected_with_evidence', '—')} rejected with evidence"
                     if fix else ("no findings" if not f else "fix PENDING"))
        out.append(f"| {key} | {', '.join(files)} | {counts} | {fixed} | {'; '.join(logs)} |")
        highs = [x for x in f if x.get("severity") in ("high", "medium")]
        if highs:
            details.append(f"\n### {key}: high and medium findings")
            for x in highs:
                problem = re.sub(r"\s+", " ", x.get("problem", ""))[:400]
                details.append(f"- **{x.get('severity', '').upper()} {x.get('id', '')}** ({x.get('kind', '')}): {problem}")
            if rev.get("overall"):
                details.append(f"- _Reviewer's overall verdict:_ {re.sub(r'\\s+', ' ', str(rev['overall']))[:600]}")
    out += details
    out += ["", "## Cross-note review", "",
            "Cross-note contradictions are resolved by the lead in `docs/research/lead-decisions.md` (each row cites the primary source or the brief text that settles it), and the gap between 11a and 11b is filled by `11c-routes-network-changes.md`. A fresh independent reviewer checked those decisions and the lead's notes (11c, 14, 15) against the binding brief; its findings and their resolutions are listed below. The workflow's automated cross-note stage was cut to stay near the brief's research checkpoint (decision D-010)."]
    with open(os.path.join(ROOT, "docs", "research", "research-review.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote docs/research/research-review.md")


if __name__ == "__main__":
    main()
